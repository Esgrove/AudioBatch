/// Copies an output stream into unsigned parser input.
std::vector<std::uint8_t> payloadBytes(const juce::MemoryOutputStream& stream)
{
    const std::span bytes {static_cast<const std::uint8_t*>(stream.getData()), stream.getDataSize()};
    return {bytes.begin(), bytes.end()};
}

/// Writes a counted two-anchor grid with deliberately nonzero opaque footer.
std::vector<std::uint8_t> gridPayload()
{
    juce::MemoryOutputStream output;
    output.writeByte(1);
    output.writeByte(0);
    output.writeIntBigEndian(2);
    output.writeIntBigEndian(std::bit_cast<int>(-0.25F));
    output.writeIntBigEndian(4);
    output.writeIntBigEndian(std::bit_cast<int>(2.0F));
    output.writeIntBigEndian(std::bit_cast<int>(128.0F));
    output.writeByte(37);
    return payloadBytes(output);
}

/// Adds a length-delimited synthetic marker record to a decoded Markers2 body.
void markerRecord(juce::MemoryOutputStream& output, const char* name, std::span<const std::uint8_t> bytes)
{
    output.writeString(name);
    output.writeIntBigEndian(static_cast<int>(bytes.size()));
    output.write(bytes.data(), bytes.size());
}

/// Encloses a decoded Markers2 body in its versioned Base64 envelope and zero padding.
std::vector<std::uint8_t> markerEnvelope(const juce::MemoryOutputStream& body)
{
    juce::MemoryOutputStream output;
    output.writeByte(1);
    output.writeByte(1);
    const auto text = juce::Base64::toBase64(body.getData(), body.getDataSize()).trimCharactersAtEnd("=");
    output.writeString(text);
    output.writeByte(0);
    return payloadBytes(output);
}

/// Constructs cue, loop, colour and lock records separated by an unknown record.
std::vector<std::uint8_t> markerPayload()
{
    juce::MemoryOutputStream body;
    body.writeByte(1);
    body.writeByte(1);
    const std::array<std::uint8_t, 16> cue {
        0,
        7,
        0,
        0,
        4,
        210,
        0,
        204,
        32,
        17,
        0,
        0,
        'C',
        'u',
        'e',
        0,
    };
    const std::array<std::uint8_t, 26> loop {0,   2, 0,  0,   3,   232, 0, 0,   7,   208, 255, 255, 255,
                                             255, 0, 39, 170, 225, 0,   1, 'I', 'n', 't', 'r', 'o', 0};
    const std::array<std::uint8_t, 3> unknown {255, 0, 99};
    const std::array<std::uint8_t, 4> colour {0, 20, 40, 60};
    const std::array<std::uint8_t, 1> lock {1};
    markerRecord(body, "CUE", cue);
    markerRecord(body, "FUTURE", unknown);
    markerRecord(body, "LOOP", loop);
    markerRecord(body, "COLOR", colour);
    markerRecord(body, "BPMLOCK", lock);
    body.writeByte(0);
    return markerEnvelope(body);
}

/// Returns fixed-width synthetic Autotags, including a negative auto gain.
std::vector<std::uint8_t> autotagsPayload()
{
    const auto bytes = std::to_array(
        "\x01\x01"
        "128.00\0-3.257\0"
        "0.000"
    );
    return {bytes.begin(), bytes.end()};
}
