#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["numpy>=2.0"]
# ///
"""
Generate independent PCM16 spectrogram inputs and sparse linear-power expectations.

Run with uv run --script fixtures/spectrogram_expected.py, or add --check to compare
regenerated bytes without writing anything.
The reference uses NumPy's double-precision FFT, not either application's DSP code.
Signals are rounded to float32, quantized to PCM16 without dither, then decoded to
float32 before measuring, so expectations describe the actual committed audio.
Noise is periodic, with an ideal frequency cutoff before PCM quantization;
window leakage and quantization noise above the cutoff are intentionally retained.
Only selected bins and frame centers are recorded, not full spectrogram grids.
Mel landmarks do not prescribe how an implementation maps bins onto display rows.
"""

import argparse
import io
import json
import shutil
import subprocess
import sys
import wave
from pathlib import Path

import numpy as np

OUTPUT_DIRECTORY = Path(__file__).resolve().parent / "spectrogram_expected"
FFT_SIZE = 4096
HOP_SIZE = 1024
MEL_ROWS = 512
MEL_SCALE = 2595.0
MEL_BREAK_HZ = 700.0
SAMPLE_RATES = (44100, 48000, 96000)
DURATION_DENOMINATOR = 5
PCM_SCALE = 32768.0
SAMPLE_WIDTH_BYTES = 2
AUDIO_ARRAY_DIMENSIONS = 2
TONE_BIN = 85
SECOND_TONE_BIN = 341
NOISE_SEED = 20261103
NOISE_PEAK = 0.75
FILTER_CUTOFFS_HZ = (16000, 18000)
PROBE_FREQUENCIES_HZ = (1000, 8000, 15900, 16000, 16100, 17900, 18000, 18100, 20000, 22000)
MEL_LANDMARKS_HZ = (0.0, 100.0, 700.0, 1000.0, 8000.0, 16000.0, 18000.0)
WINDOW = 0.5 - 0.5 * np.cos(2.0 * np.pi * np.arange(FFT_SIZE, dtype=np.float64) / (FFT_SIZE - 1))
WINDOW_SUM = float(WINDOW.sum())


def hz_to_mel(frequency: float) -> float:
    """Convert Hertz to the specified base-ten Mel scale independently of production code."""
    return float(MEL_SCALE * np.log10(1.0 + frequency / MEL_BREAK_HZ))


def mel_to_hz(mel: float) -> float:
    """Invert the base-ten Mel scale in double precision."""
    return float(MEL_BREAK_HZ * (10.0 ** (mel / MEL_SCALE) - 1.0))


def periodic_noise(frame_count: int, sample_rate: int, cutoff_hz: float) -> np.ndarray:
    """Build seeded periodic broadband noise, ideally filtered before float32 conversion."""
    generator = np.random.Generator(np.random.PCG64(NOISE_SEED))
    # Integer draws avoid relying on a library-specific normal-distribution transform.
    components = generator.integers(-32768, 32768, size=(2, frame_count // 2 + 1))
    spectrum = components[0].astype(np.float64) + 1j * components[1].astype(np.float64)
    spectrum[0] = 0.0
    spectrum[-1] = spectrum[-1].real
    frequencies = np.fft.rfftfreq(frame_count, d=1.0 / sample_rate)
    spectrum[frequencies > cutoff_hz] = 0.0
    audio = np.fft.irfft(spectrum, n=frame_count)
    return (audio * (NOISE_PEAK / np.max(np.abs(audio)))).astype(np.float32)[:, None]


def signal_cases(sample_rate: int) -> dict[str, tuple[np.ndarray, dict]]:
    """Return short mono/stereo signals and source parameters at one sample rate."""
    frame_count = sample_rate // DURATION_DENOMINATOR
    phase = 2.0 * np.pi * np.arange(frame_count, dtype=np.float64) / FFT_SIZE
    tone = (0.5 * np.sin(TONE_BIN * phase)).astype(np.float32)
    two_tones = (0.35 * np.sin(TONE_BIN * phase) + 0.15 * np.sin(SECOND_TONE_BIN * phase)).astype(np.float32)
    cases = {
        "silence": (np.zeros((frame_count, 1), dtype=np.float32), {"kind": "silence"}),
        "tone": (tone[:, None], {"kind": "tone", "tone_bins": [TONE_BIN], "amplitudes": [0.5]}),
        "antiphase": (
            np.column_stack((two_tones, -two_tones)),
            {"kind": "antiphase", "tone_bins": [TONE_BIN, SECOND_TONE_BIN], "amplitudes": [0.35, 0.15]},
        ),
    }
    for cutoff in (*FILTER_CUTOFFS_HZ, sample_rate * 0.5):
        name = "noise_full" if cutoff == sample_rate * 0.5 else f"noise_{cutoff}hz"
        cases[name] = (
            periodic_noise(frame_count, sample_rate, cutoff),
            {"kind": "periodic_noise", "cutoff_hz": cutoff, "seed": NOISE_SEED, "peak_before_quantization": NOISE_PEAK},
        )
    if sample_rate == SAMPLE_RATES[1]:
        cases["dc"] = (np.full((frame_count, 1), 0.25, dtype=np.float32), {"kind": "dc", "amplitude": 0.25})
        alternating = np.where(np.arange(frame_count) % 2 == 0, 0.5, -0.5).astype(np.float32)
        cases["nyquist"] = (alternating[:, None], {"kind": "nyquist", "amplitude": 0.5})
    return cases


def encode_pcm16(audio: np.ndarray, sample_rate: int) -> tuple[bytes, np.ndarray]:
    """Encode float32 input as standard WAV and return exactly its decoded PCM values."""
    if audio.dtype != np.float32 or audio.ndim != AUDIO_ARRAY_DIMENSIONS or not np.isfinite(audio).all():
        message = "Expected finite float32 samples in frames-by-channels order"
        raise ValueError(message)
    quantized = np.rint(audio.astype(np.float64) * PCM_SCALE)
    pcm = np.clip(quantized, -PCM_SCALE, PCM_SCALE - 1.0).astype("<i2")
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as writer:
        writer.setnchannels(audio.shape[1])
        writer.setsampwidth(SAMPLE_WIDTH_BYTES)
        writer.setframerate(sample_rate)
        writer.writeframes(pcm.tobytes())
    decoded = (pcm.astype(np.float32) / np.float32(PCM_SCALE)).astype(np.float32)
    return buffer.getvalue(), decoded


def frame_power(audio: np.ndarray, center: int) -> np.ndarray:
    """Measure a centered zero-padded Hann frame and average powers, never channel amplitudes."""
    start = center - FFT_SIZE // 2
    source_start = max(0, start)
    source_stop = min(len(audio), start + FFT_SIZE)
    frame = np.zeros((FFT_SIZE, audio.shape[1]), dtype=np.float64)
    destination_start = source_start - start
    frame[destination_start : destination_start + source_stop - source_start] = audio[source_start:source_stop]
    spectrum = np.fft.rfft(frame * WINDOW[:, None], axis=0)
    powers = (spectrum.real**2 + spectrum.imag**2) * (4.0 / WINDOW_SUM**2)
    powers[0] *= 0.25
    powers[-1] *= 0.25
    return powers.mean(axis=1)


def probe_bins(sample_rate: int) -> list[int]:
    """Select tone neighbors, cutoff neighborhoods, DC, and Nyquist without mel-row assumptions."""
    bins = {0, 1, FFT_SIZE // 2 - 1, FFT_SIZE // 2}
    for tone_bin in (TONE_BIN, SECOND_TONE_BIN):
        bins.update((tone_bin - 1, tone_bin, tone_bin + 1))
    bins.update(round(frequency * FFT_SIZE / sample_rate) for frequency in PROBE_FREQUENCIES_HZ)
    return sorted(bin_index for bin_index in bins if 0 <= bin_index <= FFT_SIZE // 2)


def describe_audio(audio: np.ndarray, sample_rate: int, source: dict) -> dict:
    """Record sparse reference powers at the leading, fully interior, and final padded centers."""
    centers = list(range(0, len(audio), HOP_SIZE))
    selected_centers = sorted({centers[0], centers[len(centers) // 2], centers[-1]})
    bins = probe_bins(sample_rate)
    return {
        "sample_rate": sample_rate,
        "channels": audio.shape[1],
        "sample_count": len(audio),
        "frame_count": len(centers),
        "source": source,
        "probe_bins": bins,
        "probe_frequencies_hz": [bin_index * sample_rate / FFT_SIZE for bin_index in bins],
        "frames": [
            {"center_sample": center, "powers": frame_power(audio, center)[bins].tolist()}
            for center in selected_centers
        ],
    }


def mel_expectations(sample_rate: int) -> dict:
    """Record analytic landmarks, inverse roundtrips, and selected linear-Mel row boundaries."""
    nyquist = sample_rate * 0.5
    landmarks = sorted({*MEL_LANDMARKS_HZ, nyquist})
    boundary_indices = (0, 1, MEL_ROWS // 4, MEL_ROWS // 2, 3 * MEL_ROWS // 4, MEL_ROWS - 1, MEL_ROWS)
    return {
        "sample_rate": sample_rate,
        "nyquist_hz": nyquist,
        "landmarks": [
            {"hz": frequency, "mel": hz_to_mel(frequency), "roundtrip_hz": mel_to_hz(hz_to_mel(frequency))}
            for frequency in landmarks
        ],
        "boundaries": [
            {
                "index": index,
                "mel": hz_to_mel(nyquist) * index / MEL_ROWS,
                "hz": mel_to_hz(hz_to_mel(nyquist) * index / MEL_ROWS),
            }
            for index in boundary_indices
        ],
    }


def generate_outputs() -> dict[str, bytes]:
    """Generate all artifacts in memory, so checking never changes committed fixtures."""
    outputs = {}
    files = {}
    for sample_rate in SAMPLE_RATES:
        for name, (audio, source) in signal_cases(sample_rate).items():
            filename = f"{name}_{sample_rate}.wav"
            encoded, decoded = encode_pcm16(audio, sample_rate)
            outputs[filename] = encoded
            files[filename] = describe_audio(decoded, sample_rate, source)
    expectations = {
        "schema_version": 1,
        "contract": {
            "fft_size": FFT_SIZE,
            "hop_size": HOP_SIZE,
            "window": "symmetric_hann",
            "window_sum": WINDOW_SUM,
            "frame_centers": "m * hop_size, starting at zero, strictly below sample_count",
            "padding": "zeros before and after the source",
            "power": "abs(rfft(window * samples))^2 * 4 / sum(window)^2",
            "dc_nyquist_power": "abs(rfft(window * samples))^2 / sum(window)^2",
            "channels": "arithmetic mean of per-channel powers",
            "power_units": "linear amplitude squared, not decibels or quantized display values",
            "probe_order": "each frame powers array follows its file probe_bins array",
            "pcm_quantization": "float32 input, round to nearest even after multiplying by 32768, saturate to int16",
            "mel_formula": "2595 * log10(1 + hz / 700)",
            "mel_rows": MEL_ROWS,
            "mel_boundaries": "linear mel from zero to source Nyquist; no bin-to-row assignment specified",
        },
        "mel": [mel_expectations(sample_rate) for sample_rate in SAMPLE_RATES],
        "files": files,
    }
    outputs["expected.json"] = jq_formatted(json.dumps(expectations, indent=2, allow_nan=False))
    return outputs


def jq_formatted(text: str) -> bytes:
    """
    Format JSON exactly as the repository format check does, so both checks accept the same bytes.

    Python and jq print floating-point numbers differently, and format.sh rewrites every tracked JSON file with jq.
    """
    jq = shutil.which("jq")
    if jq is None:
        sys.exit("jq not found in path, it formats the expected JSON like format.sh")
    command = [jq, "--indent", "2", "."]
    return subprocess.run(command, input=text.encode(), capture_output=True, check=True).stdout  # noqa: S603


def main() -> None:
    """Write artifacts, or report stale/missing artifacts with a nonzero check exit status."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Regenerate in memory and compare every artifact byte")
    arguments = parser.parse_args()
    outputs = generate_outputs()
    if arguments.check:
        stale = [
            name
            for name, data in outputs.items()
            if not (OUTPUT_DIRECTORY / name).is_file() or (OUTPUT_DIRECTORY / name).read_bytes() != data
        ]
        unexpected = (
            sorted(path.name for path in OUTPUT_DIRECTORY.iterdir() if path.is_file() and path.name not in outputs)
            if OUTPUT_DIRECTORY.is_dir()
            else []
        )
        if stale or unexpected:
            parser.exit(
                1, f"Stale or missing: {', '.join(stale) or 'none'}; unexpected: {', '.join(unexpected) or 'none'}\n"
            )
        print(f"Checked {len(outputs)} spectrogram artifacts; all bytes match")
        return
    OUTPUT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    for name, data in outputs.items():
        (OUTPUT_DIRECTORY / name).write_bytes(data)
    print(f"Wrote {len(outputs)} spectrogram artifacts ({sum(map(len, outputs.values()))} bytes)")


if __name__ == "__main__":
    main()
